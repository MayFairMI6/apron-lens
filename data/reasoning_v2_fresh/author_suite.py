def fact(prop,value,sup=(),start=None,end=None):
 result={'property':prop,'value':value,'supersedes':list(sup)}
 if start is not None:result['validFrom']=start
 if end is not None:result['validUntil']=end
 return result

def event(eid,facts,t,r=None,a='A2',flight='F2-R4',source='fictional-turnaround-coordinator'):
 return dict(id=eid,aircraftId=a,flightInstance=flight,source=source,eventTime=t,receiptTime=t if r is None else r,
             message='; '.join(f"{f['property']} reported as {f['value']}" for f in facts),facts=facts)

def gold(fid,value,status):
 return dict(fact_id=fid,value=value,status=status,evidence_ids=[fid.split(':')[0]])

def query(t,kind,props,claims=(),unknown=(),question=None):
 return dict(checkpoint=t,queryType=kind,properties=props,gold=dict(claims=list(claims),unknown_properties=list(unknown)),
             question=question or f"Review {kind} evidence for {', '.join(props) or 'this flight'} at {t} seconds.")

